"""Versioned JSON Schemas generated from the Pydantic domain models.

These files are generated by ``uv run python scripts/generate_contracts.py`` and
committed so that CI, the web client and external reviewers can validate fixtures
without a Python toolchain. **Do not edit them by hand** - edit the models.
"""

from __future__ import annotations

import functools
import json
import pathlib
from typing import Any

__all__ = ["SCHEMA_DIR", "load_all", "load_schema", "schema_index", "schema_path"]

SCHEMA_DIR = pathlib.Path(__file__).parent / "schemas"


@functools.cache
def load_all() -> dict[str, dict[str, Any]]:
    """All generated schemas, keyed by title."""
    out: dict[str, dict[str, Any]] = {}
    for path in sorted(SCHEMA_DIR.glob("*.json")):
        if path.name == "index.json":
            continue
        data: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
        title = str(data.get("title", path.stem))
        out[title] = data
    return out


@functools.cache
def schema_index() -> dict[str, Any]:
    data: dict[str, Any] = json.loads((SCHEMA_DIR / "index.json").read_text(encoding="utf-8"))
    return data


def schema_path(title: str) -> pathlib.Path:
    return SCHEMA_DIR / f"{title}.json"


@functools.cache
def load_schema(title: str) -> dict[str, Any]:
    return load_all()[title]
